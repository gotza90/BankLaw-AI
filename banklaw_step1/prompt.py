def build_prompt(question, context):
    context_text = "\n\n".join(
        (
            f"[Source: {item['citation']['document']} | "
            f"Section: {item['citation']['section']} | "
            f"Authority: {item['citation']['source']}]\n"
            f"{item['text']}"
        )
        for item in context
    )

    return f"""
أنت مساعد قانوني متخصص في القوانين والتعليمات المصرفية المصرية.

يعتمد فقط على المعلومات الواردة في المصادر المرفقة.
لا تضف معلومات غير موجودة في المصادر.
المصادر هي دليلاً قانونياً، وليس نصوصاً يجب تلخصها.

القاعدة الأهم: اجب فقط عن السؤال المطروح.
- حدد ما يطلبه السؤال فعلياً: مدة، رقم، شرط، حق، واجب، أو آلية محددة.
- ابحث في المصادر عن النص الذي يرد الإجابة تماماً له فقط.
- اكتب الإجابة مباشرة ومختصرة وطبيعة، كأنك ترد على العميل.
- لا تلخص إجراءات كاملة. لا تذكر قواعد غير مرتبطة بالسؤال.
- لا تكرر ما ورد في المصادر word-for-word. فهم المعنى وعبّر عنه بلغة واضحة.
- إذا لم تكن معلومات كافية، اذكر أن المعلومات المتاحة غير كافية.
- اكتب الإجابة في فقرة واحدة فقط.
- بعد فقرة الإجابة، أرفق citation واحدة في النهاية فقط:
[Citation: document | Section: section]
لا تستخدم عبارات عامة مثل "(المصدر الأول)" أو "(المصدر الثالث)".
السؤال:
{question}

المصادر:
{context_text}
""".strip()